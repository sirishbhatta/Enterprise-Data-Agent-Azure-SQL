-- ============================================================
-- Read-only user for the Sales database (Oracle XE)
-- Run as SYSTEM in SQL Developer, connected to XEPDB1.
-- Replace CHANGE_ME_STRONG_PASSWORD before running.
-- ============================================================

CREATE USER BI_READER IDENTIFIED BY "CHANGE_ME_STRONG_PASSWORD";
GRANT CREATE SESSION TO BI_READER;

-- Read-only access to the BI_SALES tables
GRANT SELECT ON BI_SALES.REGIONS      TO BI_READER;
GRANT SELECT ON BI_SALES.SALES_REPS   TO BI_READER;
GRANT SELECT ON BI_SALES.CUSTOMERS    TO BI_READER;
GRANT SELECT ON BI_SALES.PRODUCTS     TO BI_READER;
GRANT SELECT ON BI_SALES.ORDERS       TO BI_READER;
GRANT SELECT ON BI_SALES.ORDER_ITEMS  TO BI_READER;
GRANT SELECT ON BI_SALES.ACTIVITIES   TO BI_READER;

-- Synonyms so unqualified names like "FROM customers" still work
CREATE SYNONYM BI_READER.REGIONS      FOR BI_SALES.REGIONS;
CREATE SYNONYM BI_READER.SALES_REPS   FOR BI_SALES.SALES_REPS;
CREATE SYNONYM BI_READER.CUSTOMERS    FOR BI_SALES.CUSTOMERS;
CREATE SYNONYM BI_READER.PRODUCTS     FOR BI_SALES.PRODUCTS;
CREATE SYNONYM BI_READER.ORDERS       FOR BI_SALES.ORDERS;
CREATE SYNONYM BI_READER.ORDER_ITEMS  FOR BI_SALES.ORDER_ITEMS;
CREATE SYNONYM BI_READER.ACTIVITIES   FOR BI_SALES.ACTIVITIES;
