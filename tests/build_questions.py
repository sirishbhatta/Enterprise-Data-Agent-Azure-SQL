"""
Builds tests/questions.yaml (100 questions) from templates.
Only columns already confirmed in the schema are used.
Every 4th question is held out.
Run once:  python tests/build_questions.py
"""
import os
import yaml

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "questions.yaml")
Q = []

def add(domain, text):
    Q.append({"domain": domain, "question": text})

# HR (hr_employees: emp_id, name, department, salary, hire_date)
for dept_agg in ["What is the average salary by department?",
                 "What is the total salary paid by department?",
                 "What is the highest salary in each department?",
                 "What is the lowest salary in each department?",
                 "How many employees are in each department?",
                 "What is the average salary in each department, highest first?"]:
    add("HR", dept_agg)
for y in range(2019, 2026):
    add("HR", f"Which employees were hired after January 1, {y}?")
    add("HR", f"How many employees were hired in {y}?")
for s in [80000, 100000, 120000, 140000, 160000]:
    add("HR", f"Which employees earn more than {s}?")
for n in [3, 5, 10]:
    add("HR", f"Who are the top {n} highest paid employees?")
add("HR", "How many employees are there?")
add("HR", "What is the average salary across all employees?")
add("HR", "List all departments.")
add("HR", "What is the most recent hire date?")

# CLAIMS (Claims: ClaimID, MemberID, ServiceDate, ProviderName, DiagnosisCode,
#         ProcedureCode, BilledAmount, PaidAmount, ClaimStatus)
for st in ["Approved", "Denied"]:
    add("CLAIMS", f"How many claims have status {st}?")
    add("CLAIMS", f"What is the total billed amount for {st} claims?")
    add("CLAIMS", f"What is the total paid amount for {st} claims?")
for n in [3, 5, 10]:
    add("CLAIMS", f"Which {n} providers have the most claims?")
    add("CLAIMS", f"Which {n} providers have the highest total billed amount?")
    add("CLAIMS", f"What are the top {n} diagnosis codes by number of claims?")
    add("CLAIMS", f"What are the top {n} procedure codes by number of claims?")
for y in range(2022, 2026):
    add("CLAIMS", f"How many claims were filed in {y}?")
    add("CLAIMS", f"What is the total billed amount for service dates in {y}?")
add("CLAIMS", "How many claims are there in total?")
add("CLAIMS", "What is the total paid amount across all claims?")
add("CLAIMS", "What is the average billed amount per claim?")
add("CLAIMS", "What is the average paid amount per claim?")
add("CLAIMS", "Show the 10 largest billed claims.")
add("CLAIMS", "Show the 5 claims with the highest paid amount.")
add("CLAIMS", "How many distinct members have claims?")

# SALES (customers: customer_id, company_name; orders: customer_id, deal_value;
#        regions: region_name; products; sales_reps)
for n in [3, 5, 10]:
    add("SALES", f"Which {n} customers have the highest total order value?")
    add("SALES", f"List the {n} customers with the most orders.")
    add("SALES", f"Show the {n} largest orders by value.")
for n in [5, 10, 20]:
    add("SALES", f"List the first {n} products.")
add("SALES", "How many customers are there?")
add("SALES", "How many orders are there?")
add("SALES", "What is the total order value?")
add("SALES", "What is the average order value?")
add("SALES", "What is the largest order value?")
add("SALES", "List all sales regions.")
add("SALES", "How many sales regions are there?")
add("SALES", "List all sales reps.")
add("SALES", "How many sales reps are there?")
add("SALES", "How many products are there?")
add("SALES", "How many orders does each customer have? Show the top 10.")
add("SALES", "What is the total order value for each customer? Show the top 10.")

add("HR", "How many employees earn more than 100000?")
add("HR", "How many employees were hired before 2020?")
add("HR", "What is the total salary of all employees?")

add("CLAIMS", "What is the total billed amount for all claims?")
add("CLAIMS", "How many claims have a billed amount above 1000?")
add("CLAIMS", "How many claims have a paid amount of zero?")
add("CLAIMS", "Which provider has the highest paid amount overall?")

add("SALES", "How many customers have no orders?")
add("SALES", "Which customer has the single largest order?")
add("SALES", "How many customers have placed at least one order?")
add("SALES", "What is the total order value for customers with more than 5 orders?")

assert len(Q) == 100, f"expected 100, got {len(Q)}"

out = []
for i, q in enumerate(Q, 1):
    out.append({
        "id": f"{q['domain'].lower()}_{i:03d}",
        "question": q["question"],
        "domain": q["domain"],
        "expect_min_rows": 1,
        "held_out": i % 4 == 0,   # every 4th question is held out (25 total)
    })

header = ("# Generated by tests/build_questions.py. Edit the script, not this file.\n"
          "# held_out: true questions are for checking changes after the fact.\n")
with open(OUT, "w", encoding="utf-8") as f:
    f.write(header)
    yaml.safe_dump(out, f, sort_keys=False, allow_unicode=True)
print(f"wrote {len(out)} questions, {sum(q['held_out'] for q in out)} held out -> {OUT}")
